CREATE TABLE obfs_domains (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain VARCHAR(255) NOT NULL,
    is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_obfs_domains_domain on obfs_domains(domain);

CREATE TYPE agent_status AS ENUM('pending', 'active', 'offline', 'disabled');

CREATE TABLE agents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(32) NOT NULL,
    client_id varchar(64) NOT NULL,
    client_secret_hash varchar(255) NOT NULL,
    status agent_status NOT NULL DEFAULT 'pending',
    address varchar(255) NOT NULL,
    protocol varchar(16) NOT NULL, -- shadowsocks/anytls/hy2/vless+reality
    port_base int NOT NULL,
    stat_base int NOT NULL,
    port_capacity int NOT NULL DEFAULT 4096,
    max_sub_count int NOT NULL,
    rate DECIMAL(5, 4) NOT NULL DEFAULT 1.00, -- 0.0001 - 9.9999
    weight int NOT NULL DEFAULT 1,
    monthly_traffic_bytes bigint,
    traffic_reset_day int NOT NULL DEFAULT 1,
    labels jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_agents_client_id ON agents (client_id);

CREATE INDEX idx_agents_status ON agents (status);

CREATE INDEX idx_agents_labels ON agents USING GIN (labels);

CREATE TABLE agent_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id bigint NOT NULL,
    subscription_id bigint NOT NULL,
    plan_slot_id bigint NOT NULL,
    port int NOT NULL,
    proxy_config jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_agent_allocations_sub_slot ON agent_allocations(subscription_id, plan_slot_id)

CREATE INDEX idx_agent_allocations_agent_id ON agent_allocations (agent_id) WHERE is_active = TRUE;
