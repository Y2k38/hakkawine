CREATE TABLE media_assets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    file_key varchar(512) NOT NULL,
    bucket_name varchar(100) NOT NULL,
    original_filename varchar(255) NOT NULL,
    file_size bigint NOT NULL,
    mime_type varchar(100) NOT NULL,
    associated_type varchar(50), 
    associated_id bigint,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_media_polymorphic CHECK (
        (associated_type IS NULL AND associated_id IS NULL) OR 
        (associated_type IS NOT NULL AND associated_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uk_media_assets_file ON media_assets (file_key);

CREATE INDEX idx_media_assets_user ON media_assets (user_id);

CREATE INDEX idx_media_assets_associated ON media_assets (associated_type, associated_id) WHERE associated_id IS NOT NULL;

CREATE TABLE announcements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    content text NOT NULL,
    is_pinned boolean NOT NULL DEFAULT FALSE,
    status varchar(20) NOT NULL DEFAULT 'draft'
        CHECK (type IN ('draft', 'scheduled', 'published', 'offline', 'archived')),
    published_at timestamptz DEFAULT NULL,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_announcements_front ON announcements (is_pinned DESC, published_at DESC) WHERE status = 'published';

CREATE TABLE articles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    slug varchar(255) UNIQUE NOT NULL,
    summary varchar(500) DEFAULT '',
    content text NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'draft'
        CHECK (type IN ('draft', 'scheduled', 'published', 'offline', 'archived')),
    published_at timestamptz DEFAULT NULL,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_articles_slug_published ON articles (slug) WHERE status = 'published';
CREATE INDEX idx_articles_front ON articles (published_at DESC) WHERE status = 'published';
