CREATE TABLE commission_rules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL,
    name varchar(100) NOT NULL,
    reward_cycle varchar(20) NOT NULL 
        CHECK (reward_cycle IN ('first_order', 'recurring')),
    reward_type varchar(20) NOT NULL 
        CHECK (reward_type IN ('percentage', 'fixed')),
    reward_value DECIMAL(38, 18) NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT TRUE,
    sort_order int NOT NULL DEFAULT 0,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_commission_rules_product ON commission_rules(product_id);

CREATE TABLE user_commission_settlements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id bigint NOT NULL,
    beneficiary_user_id bigint NOT NULL,
    buyer_id bigint NOT NULL,
    order_id bigint NOT NULL,
    order_amount DECIMAL(38, 18) NOT NULL,
    commission_rate DECIMAL(5, 4) NOT NULL,
    commission_amount DECIMAL(38, 18) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'unlocked', 'cancelled')),
    freeze_days int NOT NULL DEFAULT 30,
    expected_unlock_at timestamptz NOT NULL,
    actual_unlocked_at timestamptz,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_user_commission_settlements_unlock ON user_commission_settlements (status, expected_unlock_at) WHERE status = 'pending';

CREATE INDEX idx_user_commission_settlements_order ON user_commission_settlements (order_id);

CREATE INDEX idx_user_commission_settlements_beneficiary ON user_commission_settlements (beneficiary_user_id, status);

CREATE TABLE user_commissions (
    user_id bigint PRIMARY KEY,
    commission_balance DECIMAL(38, 18) NOT NULL DEFAULT 0,
    total_earned DECIMAL(38, 18) NOT NULL DEFAULT 0,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE TABLE user_commission_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    action_type varchar(20) NOT NULL
        CHECK (action_type IN ('referral_reward', 'milestone_reward', 'transfer_to_balance', 'withdraw_payout', 'withdraw_reject_refund')),
    before_amount DECIMAL(38, 18) NOT NULL,
    amount DECIMAL(38, 18) NOT NULL,
    after_amount DECIMAL(38, 18) NOT NULL,
    settlement_id bigint,
    withdrawal_id bigint,
    remark varchar(255),
    inserted_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_user_commission_logs_user ON user_commission_logs (user_id, inserted_at DESC);

CREATE TABLE payout_methods (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL,
    driver varchar(32) NOT NULL, -- balance/manual_transfer/epay
    name varchar(64) NOT NULL,
    description varchar(255) NOT NULL,
    icon_url varchar(255) NOT NULL,
    min_tx_amount DECIMAL(38, 18),
    max_tx_amount DECIMAL(38, 18),
    handling_fee_fixed DECIMAL(38, 18),
    handling_fee_percent DECIMAL(38, 18),
    is_enable boolean NOT NULL DEFAULT TRUE,
    sort_order int NOT NULL DEFAULT 0,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_payout_methods_code ON payout_methods (code);

CREATE TABLE payout_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payout_method_id bigint NOT NULL,
    name varchar(64) NOT NULL,
    driver varchar(32) NOT NULL,
    config jsonb NOT NULL DEFAULT '{}'::jsonb,
    weight int NOT NULL DEFAULT 10,
    balance DECIMAL(38, 18),
    is_enable boolean NOT NULL DEFAULT TRUE,
    sort_order int NOT NULL DEFAULT 0,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE TABLE user_withdrawal_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    payout_method_id bigint NOT NULL,
    account_name varchar(64) NOT NULL,
    account_no varchar(128) NOT NULL,
    config jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_default boolean NOT NULL DEFAULT FALSE,
    is_enable boolean NOT NULL DEFAULT TRUE,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_user_withdrawal_accounts_user ON user_withdrawal_accounts (user_id);

CREATE TABLE user_withdrawal_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_no varchar(64) NOT NULL,
    gateway_tx_no varchar(128),
    user_id bigint NOT NULL,
    user_withdrawal_account_id bigint,
    payout_method_id bigint,
    payout_method varchar(32) NOT NULL,
    payout_driver varchar(32) NOT NULL,
    currency varchar(16) NOT NULL DEFAULT 'USD',
    amount DECIMAL(38, 18) NOT NULL,
    handling_fee DECIMAL(38, 18) NOT NULL DEFAULT 0,
    actual_amount DECIMAL(38, 18) NOT NULL,
    payout_account varchar(255) NOT NULL,
    payout_identity jsonb DEFAULT '{}'::jsonb,
    status varchar(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'completed', 'rejected')),
    reject_reason varchar(255),
    handled_at timestamptz,
    inserted_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_user_withdrawal_records_tx_no ON user_withdrawal_records (tx_no);

CREATE INDEX idx_user_withdrawal_records_user ON user_withdrawal_records (user_id, status);

CREATE INDEX idx_user_withdrawal_records_inserted_at ON user_withdrawal_records (inserted_at);